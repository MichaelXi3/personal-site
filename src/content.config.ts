import { defineCollection } from "astro:content";
import { glob } from "astro/loaders";
import { z } from "astro/zod";

const resume = defineCollection({
  loader: glob({ pattern: "resume.yaml", base: "./src/content" }),
  schema: z.object({
    experience: z.array(
      z.object({
        org: z.string(),
        role: z.string(),
        period: z.string(),
        url: z.url().optional(),
        repo: z.url().optional(),
        summary: z.string(),
        highlights: z.array(z.string()).default([]),
        tags: z.array(z.string()).default([]),
      }),
    ),
    education: z.array(
      z.object({
        org: z.string(),
        degree: z.string(),
        period: z.string(),
        note: z.string().optional(),
      }),
    ),
    focus: z.array(z.string()),
  }),
});

const projects = defineCollection({
  loader: glob({ pattern: "*.{md,mdx}", base: "./src/content/projects" }),
  schema: z.object({
    title: z.string(),
    summary: z.string(),
    year: z.string(),
    order: z.number().default(100),
    url: z.url().optional(),
    repo: z.url().optional(),
    tags: z.array(z.string()).default([]),
  }),
});

const blog = defineCollection({
  loader: glob({ pattern: "*.{md,mdx}", base: "./src/content/blog" }),
  schema: z.object({
    title: z.string(),
    description: z.string().default(""),
    date: z.coerce.date(),
    updated: z.coerce.date().optional(),
    tags: z.array(z.string()).default([]),
    draft: z.boolean().default(false),
  }),
});

// Album files are generated by scripts/photos.ts or scripts/unsplash.ts.
const photos = defineCollection({
  loader: glob({ pattern: "*.yaml", base: "./src/content/photos" }),
  schema: z.object({
    title: z.string(),
    date: z.string().regex(/^\d{4}-\d{2}$/),
    description: z.string().optional(),
    credit: z.object({ name: z.string(), profile: z.url(), unsplash: z.url() }).optional(),
    photos: z.array(
      z.object({
        id: z.string(),
        alt: z.string().default(""),
        thumb: z.string(),
        full: z.string(),
        width: z.number(),
        height: z.number(),
        link: z.url().optional(),
      }),
    ),
  }),
});

export const collections = { resume, projects, blog, photos };
